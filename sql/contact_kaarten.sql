-- Contactkaarten op de pagina Contact beheerbaar maken.
--
-- Het CMS-scherm Contact bewaarde de kaarten alleen in de browser van de
-- beheerder, net zoals het menu dat deed vóór site_navigatie. Bezoekers zagen
-- daardoor altijd de twee kaarten uit de code. Eén rij per kaart, lezen mag
-- iedereen, schrijven alleen wie is ingelogd in het CMS.
--
-- De titel en de introtekst van de pagina blijven in pagina_teksten staan
-- (blok A, 'contact.titel' en 'contact.intro1'); die worden hier niet herhaald.

create table if not exists contact_kaarten (
  id            bigint generated by default as identity primary key,
  volgorde      int     not null default 0,
  rol           text    not null,
  omschrijving  text,
  email         text,
  icoon         text    not null default '✉',
  zichtbaar     boolean not null default true,
  bijgewerkt_op timestamptz not null default now()
);

alter table contact_kaarten enable row level security;

drop policy if exists "contact_kaarten_public_read" on contact_kaarten;
create policy "contact_kaarten_public_read"
  on contact_kaarten for select
  to public using (true);

drop policy if exists "contact_kaarten_auth_write" on contact_kaarten;
create policy "contact_kaarten_auth_write"
  on contact_kaarten for all
  to authenticated using (true) with check (true);

-- De twee kaarten die nu in de code staan alvast als rij, zodat het scherm
-- niet leeg is. Draai je dit bestand nog eens, dan komen ze er niet dubbel in.
insert into contact_kaarten (volgorde, rol, omschrijving, email, icoon, zichtbaar)
select 1, 'Algemene informatie',
       'Voor alle vragen over Thuis in de Buurt — meedoen, een buurtinitiatief starten, samenwerken.',
       'info@thuisindebuurt.nl', '✉', true
where not exists (select 1 from contact_kaarten);

-- Deze tweede kaart staat op de website nu op verborgen; dat houden we zo,
-- zodat er na het uitvoeren niets verandert. In het CMS is hij met één
-- schakelaar weer zichtbaar te maken.
insert into contact_kaarten (volgorde, rol, omschrijving, email, icoon, zichtbaar)
select 2, 'Doneren & boek',
       'Vragen over donaties of het boek ''Leven is spelen'' van Margreet Jonkers.',
       'doneren@thuisindebuurt.org', '♥', false
where not exists (select 1 from contact_kaarten where rol = 'Doneren & boek');

