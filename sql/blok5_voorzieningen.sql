-- Bij blok 1 zijn tien "voorzieningen" van de Buurtatlas gehaald. Dat waren
-- verzonnen voorbeelden die in de code stonden (Boekhandel De Vries,
-- Restaurant De Pier) en nergens uit de database kwamen. Het idee erachter
-- blijft: bewoners moeten kunnen vinden wat er in de wijk ís — de huisarts,
-- de apotheek, het buurthuis.
--
-- Daarom een eigen tabel, zodat Margareth ze zelf bijhoudt in het CMS.
-- Velden (keuze Giovanny 30-10): naam, adres, website (mag leeg),
-- openingstijden en omschrijving. Telefoon heb ik er als extra bij gezet;
-- bij een huisarts of apotheek is dat vaak het eerste wat iemand zoekt.
--
-- Lezen mag iedereen, schrijven alleen wie is ingelogd in het CMS — zelfde
-- patroon als contact_kaarten.

create table if not exists voorzieningen (
  id             bigint generated by default as identity primary key,
  naam           text    not null,
  soort          text    not null default 'Overig',
  omschrijving   text,
  adres          text,
  lat            double precision,
  lng            double precision,
  telefoon       text,
  website        text,
  openingstijden text,
  zichtbaar      boolean not null default true,
  volgorde       int     not null default 0,
  aangemaakt_op  timestamptz not null default now(),
  bijgewerkt_op  timestamptz not null default now()
);

alter table voorzieningen enable row level security;

drop policy if exists "voorzieningen_public_read" on voorzieningen;
create policy "voorzieningen_public_read"
  on voorzieningen for select
  to public using (true);

drop policy if exists "voorzieningen_auth_write" on voorzieningen;
create policy "voorzieningen_auth_write"
  on voorzieningen for all
  to authenticated using (true) with check (true);

-- `soort` groepeert ze op de pagina en op de kaart. Vrije tekst zou tot
-- "Zorg", "zorg" en "Gezondheid" naast elkaar leiden; daarom een vaste lijst.
alter table voorzieningen drop constraint if exists voorzieningen_soort_check;
alter table voorzieningen add constraint voorzieningen_soort_check
  check (soort in ('Zorg','Winkels','Buurthuis','Overheid','Vervoer','Onderwijs','Overig'));

-- De pagina in het menu, zodat Margareth hem bij Pagina's aan en uit kan
-- zetten. Hij begint op verborgen: zo verschijnt er niets op de site zolang
-- er nog geen voorzieningen zijn ingevuld.
insert into site_navigatie (id, label, target, visible, level, volgorde)
select 'nav-13', 'Voorzieningen', '/voorzieningen', false, 0, 6
where not exists (select 1 from site_navigatie where target = '/voorzieningen');

