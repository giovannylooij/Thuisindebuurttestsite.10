begin;

-- -------------------------------------------------------------------
-- 1. Soorten voorzieningen
-- -------------------------------------------------------------------
create table if not exists public.voorziening_soorten (
  naam     text primary key,
  kleur    text not null default '#7a7363',
  volgorde int  not null default 0
);

alter table public.voorziening_soorten enable row level security;

drop policy if exists "voorziening_soorten_lezen" on public.voorziening_soorten;
create policy "voorziening_soorten_lezen" on public.voorziening_soorten
  for select to public using (true);

drop policy if exists "voorziening_soorten_schrijven" on public.voorziening_soorten;
create policy "voorziening_soorten_schrijven" on public.voorziening_soorten
  for all to public
  using      (get_my_role() = any (array['superadmin', 'redactie']))
  with check (get_my_role() = any (array['superadmin', 'redactie']));

-- De lijst van Margareth, in haar volgorde.
insert into public.voorziening_soorten (naam, kleur, volgorde) values
  ('Buurtcentra/Welzijn',         '#1faa59', 1),
  ('Gemeentelijke voorzieningen', '#1a73e8', 2),
  ('Horeca',                      '#d35400', 3),
  ('Kerk/Religie',                '#8e44d6', 4),
  ('Muziek',                      '#c2185b', 5),
  ('Scholen',                     '#2f6db5', 6),
  ('Sport',                       '#00897b', 7),
  ('Winkels',                     '#f57c00', 8),
  ('Zorg',                        '#e53935', 9),
  ('Overig',                      '#7a7363', 10)
on conflict (naam) do nothing;

-- De oude vaste lijst (Zorg, Winkels, Buurthuis, Overheid, Vervoer,
-- Onderwijs, Overig) zat als regel op de tabel. Die gaat eraf; de soorten
-- komen voortaan uit de tabel hierboven.
alter table public.voorzieningen drop constraint if exists voorzieningen_soort_check;

-- Bestaande voorzieningen naar de nieuwe namen.
update public.voorzieningen set soort = 'Buurtcentra/Welzijn'         where soort = 'Buurthuis';
update public.voorzieningen set soort = 'Gemeentelijke voorzieningen' where soort = 'Overheid';
update public.voorzieningen set soort = 'Scholen'                     where soort = 'Onderwijs';
update public.voorzieningen set soort = 'Overig'                      where soort = 'Vervoer';
-- Keuze Giovanny 18-11: de bibliotheek hoort bij Buurtcentra/Welzijn.
update public.voorzieningen set soort = 'Buurtcentra/Welzijn'
  where naam ilike 'Bibliotheek Scheveningen%' and soort = 'Overig';
-- Wat er dan nog niet in de lijst staat, wordt Overig.
update public.voorzieningen v set soort = 'Overig'
  where not exists (select 1 from public.voorziening_soorten s where s.naam = v.soort);

-- Koppeling: hernoemt Margareth een soort, dan gaan de voorzieningen
-- vanzelf mee. Een soort die nog in gebruik is, kan niet weg.
alter table public.voorzieningen drop constraint if exists voorzieningen_soort_fk;
alter table public.voorzieningen add constraint voorzieningen_soort_fk
  foreign key (soort) references public.voorziening_soorten (naam)
  on update cascade on delete restrict;

-- -------------------------------------------------------------------
-- 2. Aanmeldingen: naam van de organisatie (activiteiten)
-- -------------------------------------------------------------------
alter table public.buurtgroep_aanvragen add column if not exists organisatie text;

-- -------------------------------------------------------------------
-- 3. Snelle antwoorden (contactpagina)
-- -------------------------------------------------------------------
create table if not exists public.snelle_antwoorden (
  id        bigint generated by default as identity primary key,
  vraag     text    not null,
  antwoord  text    not null default '',
  pagina    text,               -- optioneel: link naar een pagina van de site
  volgorde  int     not null default 0,
  zichtbaar boolean not null default true
);

alter table public.snelle_antwoorden enable row level security;

drop policy if exists "snelle_antwoorden_lezen" on public.snelle_antwoorden;
create policy "snelle_antwoorden_lezen" on public.snelle_antwoorden
  for select to public using (true);

drop policy if exists "snelle_antwoorden_schrijven" on public.snelle_antwoorden;
create policy "snelle_antwoorden_schrijven" on public.snelle_antwoorden
  for all to public
  using      (get_my_role() = any (array['superadmin', 'redactie']))
  with check (get_my_role() = any (array['superadmin', 'redactie']));

