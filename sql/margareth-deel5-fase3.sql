   'clubjes', 1),
  ('Hoe kan ik me aansluiten als vrijwilliger bij Thuis in de Buurt?',
   'Vul het formulier op de pagina Doe mee in — we nemen binnen 3 werkdagen contact op voor een kennismakingsgesprek.',
   'doemee', 2),
  ('Hoe doneer ik?',
   'Op de Doneren-pagina kun je via Donorbox een eenmalige of maandelijkse bijdrage doen. Of bestel het boek — de opbrengst gaat volledig naar TIB.',
