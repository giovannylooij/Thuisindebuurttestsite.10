where not exists (select 1 from public.snelle_antwoorden);

commit;

-- De API de nieuwe tabellen en kolom laten zien.
notify pgrst, 'reload schema';

-- Controle: dit hoort drie regels terug te geven.
select 'soorten' as wat, count(*)::text as aantal from public.voorziening_soorten
union all
select 'snelle antwoorden', count(*)::text from public.snelle_antwoorden
union all
select 'voorzieningen per soort', string_agg(soort || ': ' || n, ', ')
  from (select soort, count(*) n from public.voorzieningen group by soort) x;
