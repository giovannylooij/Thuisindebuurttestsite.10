-- Wijzigingenlogboek — "wat is er veranderd, en door wie" (3-11-2026)
--
-- Giovanny: als Margareth inlogt wil ze zien wat er is aangepast en door wie,
-- zodat ze het kan nakijken en afvinken. Een wijziging gaat gewoon meteen
-- live; dit scherm is een logboek achteraf, geen wachtkamer.
--
-- Elke keer dat iemand in het CMS iets opslaat, aanmaakt of verwijdert komt
-- hier een regel bij. De regel bewaart ook de naam van het item en de oude
-- waarde, zodat het logboek leesbaar blijft als het item later weg is.
--
-- Er wordt niets aan bestaande tabellen veranderd. Veilig om twee keer te
-- draaien.

create table if not exists wijzigingen (
  id              bigint generated by default as identity primary key,

  -- Wat er is aangeraakt
  tabel           text        not null,   -- clubjes, activiteiten, partners, ...
  rij_id          text,                   -- id van het item, als tekst (tabellen
                                          -- verschillen in soort id)
  titel           text,                   -- naam van het item op het moment zelf
  soort           text        not null default 'aangepast',  -- nieuw | aangepast | verwijderd

  -- Wie het deed
  door_id         uuid,
  door_email      text,
  door_rol        text,                   -- superadmin | redactie | beheerder

  -- Wat er veranderde: [{ "veld": "omschrijving", "oud": "...", "nieuw": "..." }]
  velden          jsonb,

  -- Wat Margareth ermee deed
  status          text        not null default 'nieuw',  -- nieuw | goedgekeurd | gearchiveerd
  beoordeeld_door text,
  beoordeeld_op   timestamptz,

  aangemaakt_op   timestamptz not null default now()
);

-- Het scherm toont de nieuwste bovenaan en filtert op status.
create index if not exists wijzigingen_aangemaakt_idx on wijzigingen (aangemaakt_op desc);
create index if not exists wijzigingen_status_idx     on wijzigingen (status);

-- Dit logboek is niets voor de website: alleen wie is ingelogd mag erbij.
-- Wie wat te zien krijgt regelt het CMS zelf, net als bij de andere
-- beheerschermen.
alter table wijzigingen enable row level security;

drop policy if exists "wijzigingen_auth_all" on wijzigingen;
create policy "wijzigingen_auth_all"
  on wijzigingen for all
  to authenticated using (true) with check (true);

